from flask import Blueprint, redirect, render_template_string, url_for


teacher_dashboard_bp = Blueprint("teacher_dashboard", __name__)


@teacher_dashboard_bp.route("/teacher", methods=["GET"])
def teacher_index():
    return redirect(url_for("teacher_dashboard.teacher_login"))


@teacher_dashboard_bp.route("/teacher/login", methods=["GET"])
def teacher_login():
    return render_template_string(TEACHER_LOGIN_HTML)


@teacher_dashboard_bp.route("/teacher/dashboard", methods=["GET"])
def teacher_dashboard():
    return render_template_string(TEACHER_DASHBOARD_HTML)


